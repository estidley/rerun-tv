// SVGs are the editable masters. Android decodes these lossless local renders without an SVG runtime.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '../..');
const source = path.join(root, 'design/channel-icons');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json')));
const drawable = path.join(root, 'app/src/main/res/drawable-nodpi');
const generated = path.join(root, 'app/src/main/java/com/rerun/tv/ui/common/ChannelIconResources.kt');

(async () => {
  fs.mkdirSync(drawable, { recursive: true });
  const entries = [];
  const wordmarks = [];
  for (const item of manifest.channels) {
    const name = 'channel_' + item.slug.replaceAll('-', '_');
    const svg = fs.readFileSync(path.join(source, item.icon));
    if (/<image\b|<script\b|<foreignObject\b/i.test(svg.toString())) throw Error('Unexpected non-vector content');
    await sharp(svg).resize(256, 256).webp({ lossless: true }).toFile(path.join(drawable, name + '.webp'));
    entries.push(`    ${JSON.stringify(item.id)} to R.drawable.${name},`);
    const wordmarkName = 'channel_wordmark_' + item.slug.replaceAll('-', '_');
    const wordmark = fs.readFileSync(path.join(source, item.wordmark));
    if (/<image\b|<script\b|<foreignObject\b/i.test(wordmark.toString())) throw Error('Unexpected non-vector content');
    await sharp(wordmark).resize(400, 270, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .webp({ lossless: true }).toFile(path.join(drawable, wordmarkName + '.webp'));
    wordmarks.push(`    ${JSON.stringify(item.id)} to R.drawable.${wordmarkName},`);
  }
  fs.writeFileSync(generated, `// Generated by tools/channel-icons/render.cjs; edit the SVG masters and manifest instead.
package com.rerun.tv.ui.common

import com.rerun.tv.R

internal val channelIconResources: Map<String, Int> = mapOf(
${entries.join('\n')}
)

internal fun channelIconResource(channelId: String): Int {
    return channelIconResources[channelId] ?: if (channelId.startsWith("music:")) {
        R.drawable.channel_music_generic
    } else {
        R.drawable.channel_custom_generic
    }
}

internal val channelWordmarkResources: Map<String, Int> = mapOf(
${wordmarks.join('\n')}
)

internal fun channelWordmarkResource(channelId: String): Int {
    return channelWordmarkResources[channelId] ?: if (channelId.startsWith("music:")) {
        R.drawable.channel_wordmark_music_generic
    } else {
        R.drawable.channel_wordmark_custom_generic
    }
}
`);
  console.log(`Rendered ${entries.length} icons and ${wordmarks.length} wordmarks with stable-ID lookups.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
